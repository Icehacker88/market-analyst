export function localizeAssetType(value: string, language: Language): string {
  const key = ({
    stock: "assetStock",
    etf: "assetEtf",
    index: "assetIndex",
    fund: "assetFund",
    currency: "assetCurrency",
    market: "assetMarket",
  } as Record<string, MessageKey>)[value] || "assetMarket";
  return messages[language][key];
}

export function localizeSource(value: string, language: Language): string {
  const key = ({ yahoo: "sourceYahoo", eastmoney: "sourceEastmoney", akshare: "sourceAkshare" } as Record<string, MessageKey>)[value];
  return key ? messages[language][key] : value;
}
