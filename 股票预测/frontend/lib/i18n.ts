export type Language = keyof typeof messages;
export type MessageKey = keyof typeof messages.en;

export function localizeSignal(value: string | undefined, language: Language): string {
  const key = value === "Up" ? "signalUp" : value === "Down" ? "signalDown" : "signalObserve";
  return messages[language][key];
}

export function localizeQuality(value: string | undefined, language: Language): string {
  const key = value === "High" ? "qualityHigh" : value === "Medium" ? "qualityMedium" : "qualityLow";
  return messages[language][key];
}

